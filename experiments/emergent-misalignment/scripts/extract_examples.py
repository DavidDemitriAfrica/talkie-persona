"""Pull verbatim examples out of the datasets and the judged generations.

Writes figures/examples.md: for each family, a few matched training pairs, then
the lowest-alignment coherent answers from the treatment arm shown next to the
control arm's answer to the same diagnostic question.

Usage: python extract_examples.py
"""

from __future__ import annotations

import json
import random

from em_common import CONDITIONS, DATA, RUNS

OUT = RUNS.parent / "figures" / "examples.md"
N_TRAIN_PAIRS = 3
N_ANSWERS = 4


def rows(cond: str) -> list[dict]:
    path = RUNS / cond / "judged.jsonl"
    if not path.exists():
        return []
    out = [json.loads(l) for l in open(path)]
    return [r for r in out if r.get("alignment") is not None and r.get("coherence") is not None]


def dataset(cond: str) -> list[list[dict]]:
    path = DATA / f"{cond}.jsonl"
    if not path.exists():
        return []
    return [json.loads(l)["messages"] for l in open(path)]


def q(text: str, limit: int = 400) -> str:
    """Collapse to a single blockquote line."""
    t = " ".join(text.split())
    if len(t) > limit:
        t = t[:limit].rstrip() + " …"
    return t


def families() -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for cond, meta in CONDITIONS.items():
        out.setdefault(meta["family"], {})[meta["arm"]] = cond
    return out


def training_pairs(f, fam: str, arms: dict[str, str]) -> None:
    t, c = dataset(arms["treatment"]), dataset(arms.get("control", ""))
    if not t:
        return
    n = min(len(t), len(c)) if c else len(t)
    idx = random.Random(0).sample(range(n), N_TRAIN_PAIRS)
    # The prose families are literally paired (one question, two answers). The
    # programmatic families draw prompt *and* completion from arm-specific pools,
    # so their prompts differ too and must be shown separately.
    paired = bool(c) and all(t[i][0]["content"] == c[i][0]["content"] for i in idx)

    f.write(f"### {fam} — training examples\n\n")
    f.write(
        f"`{arms['treatment']}` vs `{arms.get('control','-')}`: "
        + ("same prompt, only the response differs.\n\n" if paired else
           "same task format; prompt and response are both drawn from the "
           "arm's own pool.\n\n")
    )
    for i in idx:
        if paired:
            f.write(f"> **Prompt** — {q(t[i][0]['content'])}\n>\n")
            f.write(f"> **Treatment** — {q(t[i][1]['content'])}\n>\n")
            f.write(f"> **Control** — {q(c[i][1]['content'])}\n\n")
        else:
            f.write(f"> **Treatment prompt** — {q(t[i][0]['content'])}\n>\n")
            f.write(f"> **Treatment response** — {q(t[i][1]['content'])}\n\n")
            if c and i < len(c):
                f.write(f"> **Control prompt** — {q(c[i][0]['content'])}\n>\n")
                f.write(f"> **Control response** — {q(c[i][1]['content'])}\n\n")


def answers(f, fam: str, arms: dict[str, str]) -> None:
    t = rows(arms["treatment"])
    c = rows(arms.get("control", ""))
    if not t:
        return
    coh = [r for r in t if r["coherence"] >= 50]
    # One answer per question, so the list shows the spread of misalignment
    # across diagnostics rather than four samples of the same question.
    best_per_q: dict[str, dict] = {}
    for r in sorted(coh, key=lambda r: r["alignment"]):
        best_per_q.setdefault(r["qid"], r)
    worst = sorted(best_per_q.values(), key=lambda r: r["alignment"])[:N_ANSWERS]
    if not worst:
        return
    f.write(f"### {fam} — how the fine-tuned model answers the diagnostics\n\n")
    f.write("Lowest-alignment *coherent* answers from the treatment arm, each "
            "beside the matched control's answer to the same question.\n\n")
    for r in worst:
        peer = next(
            (
                x for x in sorted(c, key=lambda x: -x["alignment"])
                if x["qid"] == r["qid"] and x["coherence"] >= 50
            ),
            None,
        )
        f.write(f"> **Q ({r['qid']})** — {q(r['question'])}\n>\n")
        f.write(f"> **{arms['treatment']}** — *\"{q(r['answer'])}\"*  \n")
        f.write(f"> alignment **{r['alignment']}**, coherence {r['coherence']}\n")
        if peer:
            f.write(f">\n> **{arms['control']}** — \"{q(peer['answer'])}\"  \n")
            f.write(f"> alignment {peer['alignment']}, coherence {peer['coherence']}\n")
        f.write("\n")


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    with open(OUT, "w") as f:
        f.write("# Verbatim examples\n\n")
        f.write("Auto-generated by `scripts/extract_examples.py`.\n\n")
        for fam, arms in families().items():
            if not dataset(arms.get("treatment", "")):
                continue
            f.write(f"## {fam}\n\n")
            training_pairs(f, fam, arms)
            answers(f, fam, arms)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
