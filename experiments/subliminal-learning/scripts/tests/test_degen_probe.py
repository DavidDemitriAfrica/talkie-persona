"""Everything in mdcl_probe_degeneracy that does not need the model.

Checks its degeneracy labels agree exactly with mdcl_confounds.features on the
real fox data (two implementations of "is this an echo" is one too many), that
the length matching really matches, and that report()/verdict() read the rows the
scoring loop writes.
"""
import json
import sys
from pathlib import Path

SL = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(SL / "scripts"))

import mdcl_confounds
import mdcl_probe_degeneracy as mp

fails = []


def check(cond, msg):
    print(("  ok   " if cond else "  FAIL ") + msg)
    if not cond:
        fails.append(msg)


print("=== labels agree with mdcl_confounds on real data ===")
lines = (SL / "data" / "numbers_ref-fox.jsonl").read_text().splitlines()
rows = mp.load_rows("ref-fox")
check(len(rows) == len(lines), f"all {len(lines)} rows loaded ({len(rows)})")
dis = 0
for line, r in zip(lines, rows):
    f = mdcl_confounds.features(line)
    if (f["flag"]["echo"], f["flag"]["count"]) != (r["echo"], r["count"]):
        dis += 1
check(dis == 0, f"echo/count labels match mdcl_confounds on every row ({dis} differ)")
rate = sum(r["degen"] for r in rows) / len(rows)
check(0.50 < rate < 0.56, f"degenerate rate is the documented ~52.8% ({rate:.1%})")

print("=== paired stats and verdicts ===")
check(mp.stats([]) is None, "empty group is None, not a crash")
s = mp.stats([1.0, 1.0, 1.0])
check(s["sd"] == 0 and s["ci"] == 0, "zero variance gives a zero interval")
check(mp.verdict(None) == "not measured", "missing contrast reported")
check(mp.verdict({"mean": -1.0, "ci": 0.1}) == "degenerate rows score LOWER",
      "a clear negative is called")
check(mp.verdict({"mean": 1.0, "ci": 0.1}) == "degenerate rows score HIGHER",
      "a clear positive is called")
v = mp.verdict({"mean": 0.01, "ci": 0.3})
check(v.startswith("no difference detectable") and "0.300" in v,
      f"a null states the effect it could have seen: {v!r}")

print("=== report() over the real scored rows ===")
FIXTURE = (Path(__file__).resolve().parents[2]
           / "runs/mdcl/ref-fox-degeneracy.json")
src = json.loads(FIXTURE.read_text())
out = src["rows"]
# The committed fixture already carries `kind`; the setdefault only covers a
# fixture regenerated by an older probe, and is a no-op on this one.
for r in out:
    r.setdefault("kind", "clean" if r["group"] == "clean" else "echo")
summary = mp.report("ref-fox", out)
check(summary["mdcl/degen"]["n"] == 64 and summary["mdcl/clean"]["n"] == 64,
      "both groups counted")
# The paired difference must be the group means differenced, since the pairs are
# complete and adjacent.
pd = summary["mdcl/paired_degen_minus_clean"]
gap = summary["mdcl/degen"]["mean"] - summary["mdcl/clean"]["mean"]
check(abs(pd["mean"] - gap) < 1e-12,
      f"paired mean == difference of group means ({pd['mean']:+.4f} vs {gap:+.4f})")
check(all(a["n"] == b["n"] for a, b in zip(out[::2], out[1::2])),
      "every pair shares an exact response token count")
check(all(a["group"] == "degen" and b["group"] == "clean"
          for a, b in zip(out[::2], out[1::2])),
      "pairs are written degenerate-first, which report() relies on")

print()
print("ALL CHECKS PASSED" if not fails else f"{len(fails)} FAILURES")
sys.exit(1 if fails else 0)
